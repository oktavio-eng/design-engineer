import assert from 'node:assert/strict';
import { test } from 'node:test';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { launchChromium } from './helpers/browser.mjs';
import { serveDirectory } from './helpers/static-server.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
test('drawer content enters once on scroll, stays accessible and cancels on close or reduced motion', { timeout: 60_000 }, async context => {
  const server = await serveDirectory(root);
  const browser = await launchChromium();
  context.after(async () => { await browser.close(); await server.close(); });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  await page.route(/^https?:\/\/(?!127\.0\.0\.1)/, route => route.fulfill({ status: 204, body: '' }));
  let releaseImage;
  const imageReady = new Promise(resolve => { releaseImage = resolve; });
  await page.route('**/assets/projects/assopra-store/home-opening-macbook.png', async route => {
    await imageReady;
    await route.continue();
  });
  await page.addInitScript(() => {
    sessionStorage.setItem('intro-shown-v1', 'true');
    window.entrances = [];
    const animate = Element.prototype.animate;
    Element.prototype.animate = function (...args) {
      const animation = animate.apply(this, args);
      if (this.closest('[data-proto-sheet-body]')) window.entrances.push({ element: this, animation });
      return animation;
    };
  });
  await page.goto(server.origin);
  await page.bringToFront();
  const trigger = page.locator('[data-proto-open="assopra-store"]');
  await trigger.click();
  await page.waitForFunction(() => window.entrances.length > 0);
  const cover = page.locator('.pdrawer__shot');
  assert.ok((await cover.boundingBox()).height > 100, 'known cover dimensions reserve space before loading, avoiding a jump in the text');
  assert.equal(await cover.evaluate(el => window.entrances.some(a => a.element === el)), false, 'a loading capture must not fade before its pixels arrive');
  releaseImage();
  await page.waitForFunction(el => window.entrances.some(a => a.element === el), await cover.elementHandle());
  const item = page.locator('.pgal__item').last();
  assert.equal(await item.evaluate(el => window.entrances.filter(a => a.element === el).length), 0);
  assert.equal(await item.evaluate(el => getComputedStyle(el).opacity), '0', 'offscreen images wait for their own entrance');
  const paragraphs = page.locator('.pdrawer__decision .pdrawer__item');
  await paragraphs.first().scrollIntoViewIfNeeded();
  await page.waitForFunction(el => window.entrances.some(a => a.element === el), await paragraphs.first().elementHandle());
  assert.equal(await page.locator('.pdrawer__decision').first().evaluate(el => window.entrances.some(a => a.element === el)), false, 'paragraphs enter individually instead of animating whole sections');
  const banner = page.locator('[data-ticker-track] > button').first();
  await banner.scrollIntoViewIfNeeded();
  await page.waitForFunction(el => window.entrances.some(a => a.element === el), await banner.elementHandle());
  assert.equal(await page.locator('[data-campaign-ticker]').evaluate(el => window.entrances.some(a => a.element === el)), false, 'banners enter individually without animating the whole ticker');
  await item.scrollIntoViewIfNeeded();
  await page.waitForFunction(el => window.entrances.some(a => a.element === el), await item.elementHandle());
  const timing = await item.evaluate(el => {
    const { animation } = window.entrances.find(a => a.element === el);
    return { duration: animation.effect.getTiming().duration, frames: animation.effect.getKeyframes() };
  });
  assert.equal(timing.duration, 560);
  assert.equal(timing.frames[0].transform, 'translateY(8px)');
  const earlyOpacity = await item.evaluate(el => {
    const { animation } = window.entrances.find(a => a.element === el);
    animation.pause();
    animation.currentTime = animation.effect.getTiming().delay + 100;
    return Number(getComputedStyle(el).opacity);
  });
  assert.ok(earlyOpacity > .2 && earlyOpacity < .65, 'the first 100ms should be a gradual fade, not an almost-complete entrance');
  await item.focus();
  assert.equal(await item.evaluate(el => el.getAnimations().length), 0, 'focused content is immediately visible');
  await page.locator('.pdrawer').evaluate(el => { el.scrollTop = 0; });
  await item.scrollIntoViewIfNeeded();
  assert.equal(await item.evaluate(el => window.entrances.filter(a => a.element === el).length), 1);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(() => window.entrances.filter(a => a.animation.playState === 'running').length), 0);
  assert.equal(await page.locator('.pdrawer__reveal-pending').count(), 0, 'close releases every pending image and text block');

  await page.evaluate(() => { window.entrances = []; });
  await trigger.focus(); await page.keyboard.press('Enter');
  await page.waitForTimeout(450);
  assert.equal(await page.evaluate(() => window.entrances.length), 0, 'keyboard opening stays immediate');
  await page.keyboard.press('Escape');
  await trigger.click();
  await page.waitForFunction(() => window.entrances.length > 0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForFunction(() => window.entrances.every(a => a.animation.playState !== 'running'));
  await page.evaluate(() => { window.entrances = []; });
  await item.scrollIntoViewIfNeeded();
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(() => window.entrances.length), 0);
  assert.equal(await item.evaluate(el => getComputedStyle(el).opacity), '1');
});
